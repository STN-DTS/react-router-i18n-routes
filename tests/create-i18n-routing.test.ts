import { describe, expect, it } from 'vitest';

import { I18nRoutingError, createI18nRouting } from '../src/index';
import { i18nRoutes } from './fixtures';

const routing = createI18nRouting(i18nRoutes);

describe('createI18nRouting', () => {
  it('exposes the routes and the declared languages', () => {
    expect(routing.routes).toBe(i18nRoutes);
    expect(routing.languages).toEqual(['en', 'fr']);
  });

  it('accepts an empty route list', () => {
    expect(createI18nRouting([]).languages).toEqual([]);
  });

  it.each([
    [
      'duplicate ids',
      [
        { id: 'A', file: 'a.tsx', paths: { en: '/en/a', fr: '/fr/a' } },
        { file: 'layout.tsx', children: [{ id: 'A', file: 'b.tsx', paths: { en: '/en/b', fr: '/fr/b' } }] },
      ],
      'Duplicate i18n route id [A]',
    ],
    [
      'duplicate files',
      [
        { id: 'A', file: 'a.tsx', paths: { en: '/en/a', fr: '/fr/a' } },
        { id: 'B', file: 'a.tsx', paths: { en: '/en/b', fr: '/fr/b' } },
      ],
      'Duplicate i18n route file [a.tsx]',
    ],
    [
      'a missing language',
      [
        { id: 'A', file: 'a.tsx', paths: { en: '/en/a', fr: '/fr/a' } },
        { id: 'B', file: 'b.tsx', paths: { en: '/en/b' } },
      ],
      'i18n route [B] declares languages [en]; expected [en, fr]',
    ],
    [
      'an extra language',
      [
        { id: 'A', file: 'a.tsx', paths: { en: '/en/a' } },
        { id: 'B', file: 'b.tsx', paths: { en: '/en/b', fr: '/fr/b' } },
      ],
      'i18n route [B] declares languages [en, fr]; expected [en]',
    ],
    [
      'languages that differ only by case',
      [{ id: 'A', file: 'a.tsx', paths: { en: '/en/a', EN: '/EN/a' } }],
      'Route id [A-EN] is generated by both i18n route [A] (language [en]) and i18n route [A] (language [EN])',
    ],
    [
      'route ids and languages that generate the same route id',
      [
        { id: 'PAGE', file: 'page.tsx', paths: { 'fr-CA': '/fr-ca/page', 'ca': '/ca/page' } },
        { id: 'PAGE-FR', file: 'page-fr.tsx', paths: { 'fr-CA': '/fr-ca/page-fr', 'ca': '/ca/page-fr' } },
      ],
      'Route id [PAGE-FR-CA] is generated by both i18n route [PAGE] (language [fr-CA]) and i18n route [PAGE-FR] (language [ca])',
    ],
  ])('rejects %s', (_, routes, message) => {
    expect(() => createI18nRouting(routes)).toThrow(new I18nRoutingError(message, 'INVALID_ROUTES'));
  });
});

describe('findRouteByFile / getRouteByFile', () => {
  it('finds page routes at any depth', () => {
    expect(routing.findRouteByFile('routes/index.tsx')?.id).toBe('HOME-0001');
    expect(routing.findRouteByFile('routes/protected/case/new-transaction.tsx')?.id).toBe('CASE-0002');
    expect(routing.getRouteByFile('routes/protected/dashboard.tsx').paths.fr).toBe('/fr/tableau-de-bord');
  });

  it('does not return layout routes', () => {
    expect(routing.findRouteByFile('routes/protected/layout.tsx')).toBeUndefined();
  });

  it('throws ROUTE_NOT_FOUND for an unknown file', () => {
    // @ts-expect-error -- unknown files are rejected at compile time
    expect(() => routing.getRouteByFile('routes/unknown.tsx')).toThrow(
      expect.objectContaining({ name: 'I18nRoutingError', code: 'ROUTE_NOT_FOUND' }),
    );
  });
});

describe('findRouteByPath / getRouteByPath', () => {
  it.each([
    ['/en/', 'HOME-0001', 'en', {}],
    ['/fr', 'HOME-0001', 'fr', {}],
    ['/en/dashboard', 'DASH-0001', 'en', {}],
    ['/fr/tableau-de-bord/', 'DASH-0001', 'fr', {}],
    ['/en/case/123/transactions/456', 'CASE-0001', 'en', { caseId: '123', transactionId: '456' }],
    ['/en/case/123/transactions/new', 'CASE-0002', 'en', { caseId: '123' }],
    ['/fr/dossier/123/transactions/nouvelle', 'CASE-0002', 'fr', { caseId: '123' }],
    ['/fr/dossier/%C3%A0-propos', 'CASE-0003', 'fr', {}],
    ['/fr/dossier/à-propos', 'CASE-0003', 'fr', {}],
  ])('matches %s to %s (%s)', (pathname, id, language, params) => {
    const match = routing.findRouteByPath(pathname);
    expect(match?.route.id).toBe(id);
    expect(match?.language).toBe(language);
    expect(match?.params).toEqual(params);
  });

  it('returns undefined when no page route matches', () => {
    expect(routing.findRouteByPath('/en/unknown')).toBeUndefined();
  });

  it('throws ROUTE_NOT_FOUND from getRouteByPath when no page route matches', () => {
    expect(() => routing.getRouteByPath('/en/unknown')).toThrow(
      new I18nRoutingError('No i18n route found for pathname [/en/unknown]', 'ROUTE_NOT_FOUND'),
    );
  });
});

describe('getLanguage', () => {
  it.each([
    ['/en/dashboard', 'en'],
    ['/fr/tableau-de-bord', 'fr'],
    ['/fr/not-an-i18n-route', 'fr'],
    ['/fr', 'fr'],
    ['/french/page', undefined],
    ['/api/health', undefined],
    ['/', undefined],
  ])('getLanguage(%s) is %s', (pathname, expected) => {
    expect(routing.getLanguage(pathname)).toBe(expected);
  });

  it('accepts a URL or a Request', () => {
    expect(routing.getLanguage(new URL('https://example.com/fr/tableau-de-bord?x=1'))).toBe('fr');
    expect(routing.getLanguage(new Request('https://example.com/en/dashboard'))).toBe('en');
  });
});

describe('getLanguage with acceptLanguage', () => {
  const request = (url: string, acceptLanguage?: string) =>
    new Request(url, acceptLanguage === undefined ? {} : { headers: { 'Accept-Language': acceptLanguage } });

  it('falls back to the Accept-Language header when the path has no language', () => {
    expect(routing.getLanguage(request('https://example.com/', 'fr-CA,fr;q=0.9'), { acceptLanguage: true })).toBe('fr');
  });

  it('prefers the language of the path', () => {
    expect(routing.getLanguage(request('https://example.com/en/dashboard', 'fr'), { acceptLanguage: true })).toBe('en');
  });

  it('ignores the header unless acceptLanguage is true', () => {
    expect(routing.getLanguage(request('https://example.com/', 'fr'))).toBeUndefined();
    expect(routing.getLanguage(request('https://example.com/', 'fr'), { acceptLanguage: false })).toBeUndefined();
  });

  it('returns undefined when the header has no supported language', () => {
    expect(routing.getLanguage(request('https://example.com/', 'de'), { acceptLanguage: true })).toBeUndefined();
    expect(routing.getLanguage(request('https://example.com/'), { acceptLanguage: true })).toBeUndefined();
  });

  it('only reads headers from a Request', () => {
    expect(routing.getLanguage('/', { acceptLanguage: true })).toBeUndefined();
    expect(routing.getLanguage(new URL('https://example.com/'), { acceptLanguage: true })).toBeUndefined();
  });
});

describe('getAlternateLanguages', () => {
  it('returns the other languages in declaration order', () => {
    expect(routing.getAlternateLanguages('en')).toEqual(['fr']);
    expect(routing.getAlternateLanguages('fr')).toEqual(['en']);

    const trilingual = createI18nRouting([{ id: 'A', file: 'a.tsx', paths: { en: '/en', fr: '/fr', iu: '/iu' } }]);
    expect(trilingual.getAlternateLanguages('fr')).toEqual(['en', 'iu']);
  });
});

describe('translatePath', () => {
  it('builds the matched route in another language, keeping its params', () => {
    expect(routing.translatePath('/en/case/1/transactions/2', 'fr')).toBe('/fr/dossier/1/transactions/2');
    expect(routing.translatePath('/fr/dossier/1/transactions/nouvelle', 'en')).toBe('/en/case/1/transactions/new');
    expect(routing.translatePath('/en/dashboard', 'en')).toBe('/en/dashboard');
  });

  it('appends search and hash', () => {
    expect(routing.translatePath('/en/dashboard', 'fr', { search: '?tab=2', hash: '#top' })).toBe(
      '/fr/tableau-de-bord?tab=2#top',
    );
  });

  it('round-trips params that need encoding', () => {
    const translated = routing.translatePath('/en/case/a%20b/transactions/%C3%A9', 'fr');
    expect(translated).toBe('/fr/dossier/a%20b/transactions/%C3%A9');
    expect(routing.findRouteByPath(translated ?? '')?.params).toEqual({ caseId: 'a b', transactionId: 'é' });
  });

  it('returns undefined when no page route matches', () => {
    expect(routing.translatePath('/en/unknown', 'fr')).toBeUndefined();
  });
});

describe('getPath', () => {
  it('builds the path for the requested language', () => {
    expect(routing.getPath('routes/protected/dashboard.tsx', 'en')).toBe('/en/dashboard');
    expect(routing.getPath('routes/protected/dashboard.tsx', 'fr')).toBe('/fr/tableau-de-bord');
  });

  it('fills in params and appends search and hash', () => {
    const path = routing.getPath('routes/protected/case/transaction.tsx', 'fr', {
      params: { caseId: '1', transactionId: '2' },
      search: new URLSearchParams({ q: 'a b' }),
      hash: 'details',
    });

    expect(path).toBe('/fr/dossier/1/transactions/2?q=a+b#details');
  });

  it('accepts search and hash strings with or without their prefix', () => {
    // generatePath() drops the trailing slash of '/en/'
    expect(routing.getPath('routes/index.tsx', 'en', { search: '?a=1', hash: '#top' })).toBe('/en?a=1#top');
    expect(routing.getPath('routes/index.tsx', 'en', { search: 'a=1', hash: 'top' })).toBe('/en?a=1#top');
  });

  it('always returns a root-relative path, even for paths declared without a leading slash', () => {
    const relative = createI18nRouting([{ id: 'A', file: 'a.tsx', paths: { en: 'en/about', fr: 'fr/a-propos' } }]);
    expect(relative.getPath('a.tsx', 'fr')).toBe('/fr/a-propos');
    expect(relative.findRouteByPath('/fr/a-propos')?.route.id).toBe('A');
  });

  it('does not percent-encode the path', () => {
    expect(routing.getPath('routes/protected/case/a-propos.tsx', 'fr')).toBe('/fr/dossier/à-propos');
  });

  it('throws when a required param is missing', () => {
    expect(() => routing.getPath('routes/protected/case/transaction.tsx', 'en', { params: { caseId: '1' } })).toThrow(
      /transactionId/,
    );
  });

  it('throws ROUTE_NOT_FOUND for a language the route does not have', () => {
    // @ts-expect-error -- unknown languages are rejected at compile time
    expect(() => routing.getPath('routes/index.tsx', 'de')).toThrow(
      new I18nRoutingError('No path for language [de] in i18n route [HOME-0001]', 'ROUTE_NOT_FOUND'),
    );
  });
});

describe('redirect', () => {
  it('returns a 302 redirect to the localized path by default', () => {
    const response = routing.redirect('routes/protected/dashboard.tsx', 'fr', { search: 'a=1' });
    expect(response.status).toBe(302);
    expect(response.headers.get('Location')).toBe('/fr/tableau-de-bord?a=1');
  });

  it('percent-encodes non-ASCII characters in the location and preserves existing escapes', () => {
    expect(routing.redirect('routes/protected/case/a-propos.tsx', 'fr').headers.get('Location')).toBe(
      '/fr/dossier/%C3%A0-propos',
    );

    const response = routing.redirect('routes/protected/case/transaction.tsx', 'fr', {
      params: { caseId: 'こんにちは', transactionId: '42' },
      search: 'q=été&r=%C3%A9',
      hash: 'section ß',
    });
    const location = response.headers.get('Location') ?? '';

    expect(location).toBe(
      '/fr/dossier/%E3%81%93%E3%82%93%E3%81%AB%E3%81%A1%E3%81%AF/transactions/42?q=%C3%A9t%C3%A9&r=%C3%A9#section%20%C3%9F',
    );
    expect(routing.findRouteByPath(location)?.params).toEqual({ caseId: 'こんにちは', transactionId: '42' });
  });

  it('accepts a status code or ResponseInit', () => {
    expect(routing.redirect('routes/index.tsx', 'en', { init: 301 }).status).toBe(301);

    const response = routing.redirect('routes/index.tsx', 'en', { init: { status: 303, headers: { 'X-Test': '1' } } });
    expect(response.status).toBe(303);
    expect(response.headers.get('X-Test')).toBe('1');
  });
});
